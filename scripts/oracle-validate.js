"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = process.env.NUSA_ORACLE_ROOT || "/";
const envPath = path.join(root, "etc/nusa/cloud-runtime.env");
const dbPath = path.join(root, "var/lib/nusa/cloud-state.db");
const backupPath = path.join(root, "var/backups/nusa");
const servicePath = path.join(root, "etc/systemd/system/nusa.service");
const fail = (message) => { throw new Error(message); };
if (!fs.existsSync(envPath)) fail(`missing environment file: ${envPath}`);
const env = fs.readFileSync(envPath, "utf8");
for (const key of ["NUSA_CLOUD_DASHBOARD_PORT", "NUSA_CLOUD_DASHBOARD_TOKEN", "NUSA_CLOUD_STATE_DB_PATH"]) if (!new RegExp(`^${key}=`, "m").test(env)) fail(`missing ${key}`);
const token = env.match(/^NUSA_CLOUD_DASHBOARD_TOKEN=(.*)$/m)?.[1] ?? "";
if (Buffer.byteLength(token, "utf8") < 32) fail("dashboard token must be at least 32 bytes");
if (!/^NUSA_CLOUD_DASHBOARD_HOST=(127\.0\.0\.1|localhost)$/m.test(env) && /NUSA_CLOUD_DASHBOARD_HOST=/.test(env)) fail("dashboard host must be localhost");
if (path.resolve(dbPath).startsWith(path.resolve(root, "opt/nusa/current"))) fail("database must be outside release tree");
if (!fs.existsSync(backupPath)) fail(`missing backup directory: ${backupPath}`);
if (!fs.existsSync(servicePath)) fail(`missing systemd unit: ${servicePath}`);
const unit = fs.readFileSync(servicePath, "utf8");
for (const required of ["User=nusa", "Group=nusa", "NoNewPrivileges=true", "Restart=on-failure", "WorkingDirectory=/opt/nusa/current"]) if (!unit.includes(required)) fail(`unit missing ${required}`);
console.log(JSON.stringify({ status: "PASS", envPath, dbPath, backupPath, servicePath }));
